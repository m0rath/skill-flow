"""Fetch script for acme/AcmeOS - the product's ONE script.

Generated by the advisory-script-builder skill from vendors/acme/source_study.json.
Everything specific to this product lives here: the listing and field parser hooks.
The generic engine is scripts/core.py.

Study decisions baked in (source_study.json):
  listing.content_type = json (the Content-Type header lies: text/html; the core sniffs the body)
  listing.pagination   = page   -> /advisories?page={n}
  listing.product_filter = client-side -> rows whose `products` names the target
  product_match.primary = CSAF product_tree / known_affected; page fallback table#versions
  product_match.text_fallback = div#affected p  ("Affected: AcmeOS, AcmeCloud.")
  fields.* -> see each parse_* below
"""
import re
import sys
from pathlib import Path

# This file sits at <repo>/vendors/<vendor>/<product>/run/fetch_advisories.py,
# so the repository root is four levels up. Never rely on the working directory.
REPO_ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(REPO_ROOT))

from scripts.core import collapse_ws, iso_date, keep_lines, render_text  # noqa: E402
from scripts.core import main  # noqa: E402

VENDOR = "acme"                          # exact vendors[].vendor_name from registry.json
PRODUCT = "AcmeOS"                       # exact products[].product_name from registry.json
STUDY_VERSION = "1.0"                    # source_study.json study_version this script was built from
STUDIED_AT = "2026-10-06T12:00:00Z"      # source_study.json studied_at this script was built from

PRODUCT_NAMES = {"acmeos", "acme acmeos"}          # product_match.names.match
NEVER_MATCH = {"acmecloud"}                        # product_match.names.never_match
FULL_NAME = "AcmeOS"                               # the vendor's own product name for version entries
VERS_RE = re.compile(r"^(?P<prod>.+?) vers:acme/>=(?P<lo>[^|]+)\|<=(?P<hi>.+)$")   # CSAF range leaf
BRANCH_RE = re.compile(r"^(?P<prod>.+?) (?P<branch>\d+(?:\.\d+)*)\.x$")               # CSAF branch leaf
EXACT_RE = re.compile(r"^(?P<prod>.+?) (?P<ver>\d+(?:\.\d+)+)$")                     # CSAF exact leaf
CVE_RE = re.compile(r"CVE-\d{4}-\d{4,}")


def _is_target(name) -> bool:
    n = collapse_ws(name or "")
    return bool(n) and n.lower() in PRODUCT_NAMES and n.lower() not in NEVER_MATCH


# ----------------------------------------------------------------- listing hooks
def listing_request(listing_url, product, page):
    """listing.pagination = page: /advisories?page={n}; the core stops on an empty page."""
    return listing_url, {"page": page}


def parse_listing(doc, product):
    """JSON listing rows -> [{"advisory_id", "date_published", "date_updated"}] for rows naming the target
    (listing.product_filter = client-side, rows carry `products`)."""
    rows = []
    for item in (doc or {}).get("items") or []:
        if not any(_is_target(p) for p in item.get("products") or []):
            continue
        rows.append({"advisory_id": item.get("id"), "date_published": iso_date(item.get("published")),
                     "date_updated": iso_date(item.get("updated"))})
    return rows


def detail_url(advisory_url_template, advisory_id):
    return advisory_url_template.replace("{advisory_id}", advisory_id)


# ----------------------------------------------------------------- field hooks
def _sel(doc, css):
    return doc.page.select_one(css) if doc.page is not None and hasattr(doc.page, "select_one") else None


def parse_advisory_id(doc):
    """fields.advisory_id.location = dd#advisory-id"""
    return collapse_ws(render_text(_sel(doc, "dd#advisory-id")))


def parse_cve_ids(doc):
    """CSAF first (vulnerabilities[].cve), else fields.cve_ids.location = dd#cves ('None' when there are none)."""
    if doc.csaf:
        cves = [v.get("cve") for v in doc.csaf.get("vulnerabilities") or [] if v.get("cve")]
        if cves:
            return cves
    text = render_text(_sel(doc, "dd#cves")) or ""
    return CVE_RE.findall(text)


def parse_summary(doc):
    """fields.summary.location = div#summary p; fallback fields.title.location = h1#title"""
    return collapse_ws(render_text(_sel(doc, "div#summary p"))) or collapse_ws(render_text(_sel(doc, "h1#title")))


def _csaf_versions(doc):
    """Version-contract entries from the CSAF twin: leaves in known_affected, mapped by leaf name shape
    (fields.affected_products.notes; bound_convention inclusive)."""
    leaves = {}

    def walk(branch):
        for b in branch.get("branches") or []:
            if "product" in b:
                leaves[b["product"]["product_id"]] = b["product"]["name"]
            walk(b)
    walk(doc.csaf.get("product_tree") or {})
    affected = []
    for v in doc.csaf.get("vulnerabilities") or []:
        affected += (v.get("product_status") or {}).get("known_affected") or []
    out, seen = [], set()
    for pid in affected:
        name = leaves.get(pid)
        if not name or name in seen:
            continue
        seen.add(name)
        m = VERS_RE.match(name)
        if m and _is_target(m.group("prod")):
            out.append({"product": FULL_NAME, "kind": "range", "from": m.group("lo"), "from_inclusive": True,
                        "to": m.group("hi"), "to_inclusive": True, "raw": name, "source": "csaf"})
            continue
        m = BRANCH_RE.match(name)
        if m and _is_target(m.group("prod")):
            out.append({"product": FULL_NAME, "kind": "branch", "version": m.group("branch"), "raw": name, "source": "csaf"})
            continue
        m = EXACT_RE.match(name)
        if m and _is_target(m.group("prod")):
            out.append({"product": FULL_NAME, "kind": "exact", "version": m.group("ver"), "raw": name, "source": "csaf"})
    return out


def _page_versions(doc):
    """Page fallback: table#versions rows (Product | Version | Status) with Status Affected."""
    out = []
    table = _sel(doc, "table#versions")
    for tr in (table.find_all("tr") if table is not None else []):
        cells = [collapse_ws(render_text(td)) or "" for td in tr.find_all("td")]
        if len(cells) < 3 or not _is_target(cells[0]) or cells[2].lower() != "affected":
            continue
        ver = cells[1]
        if ver.lower() == "all":
            out.append({"product": FULL_NAME, "kind": "all", "raw": f"{cells[0]} {ver}", "source": "html"})
        elif " through " in ver:
            lo, hi = ver.split(" through ", 1)
            out.append({"product": FULL_NAME, "kind": "range", "from": lo, "from_inclusive": True, "to": hi,
                        "to_inclusive": True, "raw": f"{cells[0]} {ver}", "source": "html"})
        elif re.fullmatch(r"\d+\.\d+", ver):
            out.append({"product": FULL_NAME, "kind": "branch", "version": ver, "raw": f"{cells[0]} {ver}", "source": "html"})
        else:
            out.append({"product": FULL_NAME, "kind": "exact", "version": ver, "raw": f"{cells[0]} {ver}", "source": "html"})
    return out


def parse_version_affected(doc, product):
    """CSAF first; the page only when CSAF yields nothing (never mixed)."""
    if doc.csaf:
        vs = _csaf_versions(doc)
        if vs:
            return vs
    return _page_versions(doc)


def parse_workaround(doc):
    """fields.workaround.location = div#workaround p - verbatim, line breaks kept; None when absent."""
    return keep_lines(render_text(_sel(doc, "div#workaround p")))


def parse_additional_details(doc, fields):
    """fields = the study's other_details.* + date_published locations. Only keys with a value."""
    out = {}
    # date_published chain: dd#published, then the revision-history first row
    dp = iso_date(collapse_ws(render_text(_sel(doc, "dd#published"))))
    if not dp:
        tds = [collapse_ws(render_text(td)) for td in (_sel(doc, "div#history table tr") or []).find_all("td")] \
            if _sel(doc, "div#history table tr") is not None else []
        dp = iso_date(tds[-1]) if tds else None
    if dp:
        out["date_published"] = dp
    cwe = collapse_ws(render_text(_sel(doc, "dd#cwe")))
    if cwe:
        parts = [p.strip() for p in cwe.split(",") if p.strip()]
        out["cwe_capec_mitre"] = parts if len(parts) > 1 else parts[0]
    sec = keep_lines(render_text(_sel(doc, "div#fixed p")))
    if sec:
        out["security_details"] = sec
    # bug_details, impact, discovered, attack_type, reference: study location null ("not present") -> omitted
    return out


# ----------------------------------------------------------------- checks
def affects_product(doc, product):
    """product_match.primary (CSAF known_affected leaves / page table) then text_fallback (div#affected p).
    None when neither source could be read."""
    primary = None
    if doc.csaf:
        primary = bool(_csaf_versions(doc))
    elif _sel(doc, "table#versions") is not None:
        primary = bool(_page_versions(doc))
    if primary:
        return True
    prose = collapse_ws(render_text(_sel(doc, "div#affected p")))
    if prose is None and primary is None:
        return None
    names = [n.strip(" .") for n in (prose or "").split(":", 1)[-1].split(",")]
    if any(_is_target(n) for n in names):
        return True
    return False, f"primary: {'target not named' if primary is not None else 'unreadable'}; text: {prose or 'no affected-products section'}"


def is_withdrawn(doc):
    text = collapse_ws(render_text(_sel(doc, "h1#title"))) or ""
    return "withdrawn" in text.lower()


if __name__ == "__main__":
    sys.exit(main(vendor=VENDOR, product=PRODUCT, argv=sys.argv[1:], parser=sys.modules[__name__]))
